def inline_md(s):
    s = s.replace('<b>', '**').replace('</b>', '**')
    return re.sub(r'<[^>]+>', '', s)
def to_md(blocks, title):
    out = ['## ' + title, '']
    for b in blocks:
        k = b[0]
        if k == 'p': out += [inline_md(b[1]), '']
        elif k == 'h2': out += ['### ' + b[1], '']
        elif k == 'h3': out += ['#### ' + b[1], '']
        elif k == 'ul': out += ['- ' + inline_md(x) for x in b[1]] + ['']
        elif k == 'ol': out += [str(i+1) + '. ' + inline_md(x) for i, x in enumerate(b[1])] + ['']
        elif k == 'table':
            out += ['| ' + ' | '.join(b[1]) + ' |', '|' + '---|' * len(b[1])]
            out += ['| ' + ' | '.join(inline_md(c) for c in r) + ' |' for r in b[2]] + ['']
    return '\n'.join(out)
def to_html(blocks):
    h = []
    for b in blocks:
        k = b[0]
        if k == 'p': h.append('<p>' + b[1] + '</p>')
        elif k in ('h2', 'h3'): h.append('<%s>%s</%s>' % (k, b[1], k))
        elif k in ('ul', 'ol'): h.append('<%s>' % k + ''.join('<li>' + x + '</li>' for x in b[1]) + '</%s>' % k)
        elif k == 'table':
            h.append('<div class="tw"><table><thead><tr>' + ''.join('<th>' + c + '</th>' for c in b[1]) + '</tr></thead><tbody>' + ''.join('<tr>' + ''.join('<td>' + c + '</td>' for c in r) + '</tr>' for r in b[2]) + '</tbody></table></div>')
    return ''.join(h)

